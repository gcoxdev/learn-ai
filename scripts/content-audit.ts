import type { Curriculum } from "../src/lib/model";

/** Coverage checks supplement the schema/graph validator; they do not grade teaching quality. */
export function auditContent(curriculum: Curriculum) {
  const slots = new Map<string, string>();
  for (const lesson of curriculum.lessons) {
    if (slots.has(lesson.slot))
      throw new Error(`Duplicate slot: ${lesson.slot}`);
    slots.set(lesson.slot, lesson.id);
    for (const route of Object.values(lesson.routes)) {
      if (!route.length) continue;
      const scenes = route.map((id) => lesson.scenes.find((s) => s.id === id));
      if (
        scenes.at(-2)?.type !== "assessment" ||
        scenes.at(-1)?.type !== "recap"
      )
        throw new Error(
          `Assessment must immediately precede final thought: ${lesson.id}`,
        );
      if (scenes.slice(0, -2).filter(Boolean).length < 4)
        throw new Error(`Insufficient teaching scenes: ${lesson.id}`);
    }
    if (
      new Set(lesson.questions.map((q) => q.prompt.trim())).size !==
      lesson.questions.length
    )
      throw new Error(`Repeated assessment prompt: ${lesson.id}`);
    if (lesson.scenes.some((s) => /\b(?:TODO|TBD|lorem ipsum)\b/i.test(s.html)))
      throw new Error(`Unfilled scene: ${lesson.id}`);
  }
  const expected = curriculum.catalog.flatMap((module) =>
    module.lessons.map((_, i) => `${module.id}.${i + 1}`),
  );
  const bridges = Array.from(
    { length: 23 },
    (_, i) => `B${String(i + 1).padStart(2, "0")}`,
  );
  const required = new Set([...expected, ...bridges, "A01"]);
  for (const slot of required)
    if (!slots.has(slot)) throw new Error(`Missing authored slot: ${slot}`);
  for (const slot of slots.keys())
    if (!required.has(slot)) throw new Error(`Unmapped authored slot: ${slot}`);
  if (curriculum.catalog.length !== 38 || expected.length !== 304)
    throw new Error(
      "The initial draft requires 38 modules and 304 main lessons",
    );
  return {
    main: expected.length,
    bridges: bridges.length,
    previews: 1,
    total: slots.size,
  };
}

export function coverageReport(curriculum: Curriculum) {
  const counts = auditContent(curriculum);
  return `# Initial draft coverage

${counts.main} main lessons across 38 modules, ${counts.bridges} mathematics/programming bridge overviews, and ${counts.previews} preserved advanced preview: **${counts.total} authored assets**. Every catalog slot has an initial draft with teaching scenes, sources, two assessment families with retake variants, and a final thought after the assessment.

This file is regenerated by \`npm run content\`. Canonical prose and checks live in \`content/lessons/*.yaml\`; the module descriptions and guided-path roots live in \`content/curriculum.yaml\`.

## Module coverage

| Module | Area | Authored / planned |
| --- | --- | --- |
${curriculum.catalog.map((m) => `| ${m.id} | ${m.title} | ${m.lessons.length} / ${m.lessons.length} |`).join("\n")}

## Side lessons

${curriculum.lessons
  .filter((l) => l.category === "bridge")
  .toSorted((a, b) => a.slot.localeCompare(b.slot))
  .map((l) => `- ${l.slot}: [${l.title}](lessons/${l.id}.yaml)`)
  .join("\n")}

## Scope of this draft

- The bridges are 23 initial overviews, not the future expanded bank of prerequisite micro-lessons.
- New core MoE lessons occupy M18; A01 preserves the older uncredited routing preview and its evidence IDs. Existing formal mathematics extension checks also remain uncredited practice.
- M36 supplies eight concrete projects, no-code/manual options, worked reference fragments, and self/peer-review rubrics. Quizzes check concepts; they do not grade unseen project artifacts.
- M35 pins dated report revisions and separates released weights, code, data, checkpoint lineage, and undisclosed details. Sources were checked during authoring on September 13, 2026; these are historical mechanism anchors, not a live model ranking or a guarantee that every external link stays available.
- Structural completeness is checked automatically. Independent subject review, assessment calibration, worked-example expansion, learner trials, and accessibility review remain open. Initial drafts do not establish comprehensive mastery or production-school readiness.
`;
}
