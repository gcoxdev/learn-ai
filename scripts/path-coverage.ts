import type { Curriculum } from "../src/lib/model";
import { planPath } from "../src/lib/engine";

export function pathCoverage(c: Curriculum) {
  const core = new Map<string, string[]>();
  const extensions = new Map<string, string[]>();
  const add = (map: Map<string, string[]>, lesson: string, path: string) =>
    map.set(lesson, [...new Set([...(map.get(lesson) ?? []), path])]);
  const paths = c.recipes.map((recipe) => {
    const plan = planPath(c, recipe, []);
    for (const lesson of plan.lessons) add(core, lesson.id, recipe.id);
    for (const extension of recipe.extensions) {
      const lesson = c.lessons.find((l) => l.id === extension.lesson)!;
      const branch = planPath(c, { ...recipe, roots: lesson.objectives }, []);
      for (const preparation of branch.lessons)
        add(extensions, preparation.id, recipe.id);
    }
    return { recipe, plan };
  });
  return {
    core,
    extensions,
    paths,
    unassigned: c.lessons.filter(
      (l) => !core.has(l.id) && !extensions.has(l.id),
    ),
  };
}

export function pathCoverageReport(c: Curriculum) {
  const { core, extensions, paths, unassigned } = pathCoverage(c);
  return `# System paths and curriculum coverage

Generated by \`npm run content\`. Required cores follow a stated reference design or comparative outcome. Optional extensions and their preparation remain available without changing core completion. All paths reuse the same objective evidence. Coverage here means a discoverable draft, not complete instruction or demonstrated expertise.

| Path | Core lessons | Core objectives | Endpoint |
| --- | ---: | ---: | --- |
${paths.map(({ recipe, plan }) => `| ${recipe.title} | ${plan.lessons.length} | ${plan.required.length} | [${c.lessons.find((l) => l.id === recipe.destination)!.title}](lessons/${recipe.destination}.yaml) |`).join("\n")}

${core.size} distinct lessons appear in a core. ${c.lessons.filter((l) => !core.has(l.id) && extensions.has(l.id)).length} further lessons are extensions or preparation for them. ${unassigned.length} lessons are library-only.

## Required and optional coverage by lesson

An extension path listed below may reach the lesson through that extension’s prerequisites. Shared counts never manufacture evidence for an untested objective.

| Slot | Lesson | Required in | Extension / its preparation |
| --- | --- | --- | --- |
${c.lessons.map((l) => `| ${l.slot} | [${l.title}](lessons/${l.id}.yaml) | ${(core.get(l.id) ?? []).join(", ") || "—"} | ${(extensions.get(l.id) ?? []).filter((p) => !core.get(l.id)?.includes(p)).join(", ") || "—"} |`).join("\n")}

## Remaining depth gaps

The editorial report tracks thin lessons and weak question-bank patterns. Further priorities include fuller audio/signal mathematics, spatial transforms and control mathematics, deeper video training/sampling traces, music and sound design, and autonomous-driving-specific prediction/planning/evaluation. Chatbots are a language/application variant; driving is a robotics/vision variant. Neither needs duplicate beginner foundations, but those variants still need their own detailed instruction. Formal advanced outcomes, richer retake banks, retention checks, and independent project review remain unfinished.
`;
}
