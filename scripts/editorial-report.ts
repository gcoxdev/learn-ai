import type { Curriculum } from "../src/lib/model";

export function editorialMetrics(c: Curriculum) {
  const active = c.lessons.flatMap((l) =>
    l.questions.filter((q) => !q.retired),
  );
  const choices = active.filter((q) => q.options.length > 1);
  const absolute =
    /\b(?:always|never|every|only|guarantee|automatically|necessarily|impossible)\b/i;
  const longest = choices.filter((q) => {
    const correct = q.options.find((o) => o.id === q.answers.choice)!;
    return (
      correct.text.length >= Math.max(...q.options.map((o) => o.text.length))
    );
  }).length;
  const absoluteDistractors = choices.filter(
    (q) =>
      !absolute.test(q.options.find((o) => o.id === q.answers.choice)!.text) &&
      q.options.some((o) => o.id !== q.answers.choice && absolute.test(o.text)),
  ).length;
  const binary = choices.filter(
    (q) =>
      q.options.filter((o) => /^(yes|no)[.!]?$/i.test(o.text.trim())).length >=
      2,
  ).length;
  return {
    active: active.length,
    choices: choices.length,
    longest,
    absoluteDistractors,
    binary,
    numeric: active.filter((q) => q.fields.length).length,
    shortLessons: c.lessons.filter(
      (l) => l.archetype === "mechanism" && l.teachingWords < 300,
    ),
    genericSources: c.lessons.filter((l) =>
      l.sources.every((s) =>
        ["/", "/contents.html"].includes(new URL(s.url).pathname),
      ),
    ),
  };
}
export function editorialReport(c: Curriculum) {
  const m = editorialMetrics(c);
  const pct = (n: number) =>
    `${((100 * n) / Math.max(1, m.choices)).toFixed(1)}%`;
  return `# Editorial quality signals

Generated by \`npm run content\`. These are review prompts, not a measurement of learner understanding. Retired questions and off-route legacy scenes do not count. A word floor or option-length statistic cannot establish lesson quality.

| Signal | Current active bank |
| --- | ---: |
| Active variants | ${m.active} |
| Variants with numeric fields | ${m.numeric} |
| Choice questions with a longest correct option (ties included) | ${m.longest}/${m.choices} (${pct(m.longest)}) |
| Absolutist distractor but non-absolutist correct option | ${m.absoluteDistractors}/${m.choices} (${pct(m.absoluteDistractors)}) |
| Bare yes/no pair | ${m.binary}/${m.choices} (${pct(m.binary)}) |
| Mechanism drafts below 300 teaching words | ${m.shortLessons.length} |
| Lessons citing only a textbook front door | ${m.genericSources.length} |

## Revision status

The opening eleven lessons now define everyday roles before training vocabulary. Arithmetic, functions, data, learning methods, prediction, and neurons have expanded worked instruction; selected attention, flow/energy, associative-memory, and MoE lessons have added traces. The opening banks offer four active variants per family, with changed-number input fields in arithmetic, functions, prediction, and neurons. Earlier checks remain readable to the backup validator and cannot be reused as fresh credit.

Most later lessons still require substantive editorial expansion and assessment revision. This pass does not claim that the corpus-wide assessment patterns have been eliminated. Use plausible mistakes tied to the taught mechanism; do not add universal-sounding wording to correct answers merely to manipulate these statistics. Numeric examples suit computational mechanisms, while historical and social comparisons need concrete cases and justified reasoning rather than forced arithmetic.

## Mechanism drafts to deepen

${m.shortLessons.map((l) => `- [${l.slot}: ${l.title}](lessons/${l.id}.yaml) — ${l.teachingWords} teaching words`).join("\n")}

## Source links needing a more precise reading destination

${m.genericSources.map((l) => `- [${l.slot}: ${l.title}](lessons/${l.id}.yaml)`).join("\n")}
`;
}
